#!/usr/bin/env bash

set -euo pipefail			#Enable strict mode

readonly EXIT_SUCCESS=0			#Success
readonly EXIT_USAGE=1			#Wrong argument count
readonly EXIT_FILE_NOT_FOUND=2		#File not found OR not a regular file
readonly EXIT_NOT_READABLE=3		#File not readable
readonly EXIT_EMPTY_FILE=4		#Empty file
readonly EXIT_WRITE_FAILED=5		#Failed to write summary.txt


usage(){					#prints correct script usage when input args are invalid
	echo "Usage: $0 <log_file>" >&2
}


error_exit(){					#prints an error message and exit with the specified error code
	echo "Error: $1" >&2
	exit "$2"
}


#Global counters for log statistics
TOTAL_LINES=0
ERROR_COUNT=0
WARNING_COUNT=0
INFO_COUNT=0					#improvement - count occurence of "info"
#Constants for top-words analysis
readonly MIN_WORD_LENGTH=3			#ignore words shorter than 3 characters
readonly TOP_N=3				#report only top 3 words
readonly STOP_WORDS="the a an and what how where to be been this that it is not but by of with for from at in as are were its no info error warning"

TOP_WORDS=()					#array to store the top frequent words and their count


readonly SUMMARY_FILE="${SUMMARY_FILE:-summary.txt}"			#sets output report filename to summary.txt
readonly LINE_MAJOR="========================================"		#report formatting headers definition
readonly LINE_MINOR="----------------------------------------"


validate_input(){
	local arg_count="$1"			#store the number of args passed to the script
	local log_file="${2:-}"			#store log file path (empty string if not provided)
	
	if [[ "$arg_count" -ne 1 ]]; then	#1. ensure only 1 one command-line arg is provided
		usage				#show correct usage syntax
		exit "$EXIT_USAGE"		#exit with appropriate exit code, 1
	fi

	if [[ ! -f "$log_file" ]]; then		#2. verify the path exists and is a regular file
		error_exit "'$log_file' does not exist or is not a regular file." "$EXIT_FILE_NOT_FOUND" 	#print an error message with exit code 2
	fi

	if [[ ! -r "$log_file" ]]; then		#3. check that the file is readable by current user
		error_exit "'$log_file' is not readable (check permissions)." "$EXIT_NOT_READABLE"
	fi

	if [[ ! -s "$log_file" ]]; then		#4. check if the file is empty
		error_exit "'$log_file' is empty, nothing to analyze." "$EXIT_EMPTY_FILE"
	fi
}


#Counts the number of lines which contain the given word pattern
count_matches(){
	local pattern="$1"				#word pattern to search
	local log_file="$2"				#log file to search in
	grep -iwc -- "$pattern" "$log_file" || true	#count matching lines, case-insensitive, whole word, and true prevents from exiting if no match
}


#Compute the statistics
compute_statistics(){
	local log_file="$1"					#log file to analyze

	TOTAL_LINES=$(wc -l < "$log_file")			#Find the total number of lines in the log file

	ERROR_COUNT=$(count_matches "error" "$log_file")	#Find the count of "error"

	WARNING_COUNT=$(count_matches "warning" "$log_file")	#Find the count of "warning"
	INFO_COUNT=$(count_matches "info" "$log_file")		#Find the count of "info"
}


#Finds the most frequent meaningful words
compute_top_words(){
	local log_file="$1"						#log file to analyze

	mapfile -t TOP_WORDS < <(					#read each line produced by pipeline into the TOP_WORDS array
		
		#Convert all text to lowercase
		tr '[:upper:]' '[:lower:]' < "$log_file" |

		#Replace non-letter characters with newlines to produce one word per line
		tr -cs 'a-z' '\n' |

		
		#Filter out short words and stop-words, keeping only meaningful words
		awk -v min="$MIN_WORD_LENGTH" -v stop="$STOP_WORDS" '
			BEGIN { n = split(stop, list, " ");
				for (i = 1; i <= n; i++)
					skip[list[i]] = 1
			}
			length($0) >= min && !($0 in skip)' |

		#sort words alphabteically and count occurences of each unique word
		sort | uniq -c |

		#sort by frequency (highest first), then alphabetically for equal counts
		sort -k1,1nr -k2,2 |	

		#format and print the top N words
		awk -v n="$TOP_N" 'NR <= n { printf "%d. %-12s - %d\n", NR, $2, $1 }'

	)
}


#summary generation
generate_report(){
	local log_file="$1"				#log file to analyze
	local generated_on
	local generated_by

	generated_on=$(date '+%Y-%m-%d %H:%M:%S')	#get the current date and time
	generated_by=$(basename "$0")			#extract only the script filename from $0

	echo "$LINE_MAJOR"				#generate the summary file contents
	echo "	  LOG SUMMARY REPORT"
	echo "$LINE_MAJOR"
	echo ""
	echo "Input File 	: $log_file"
	echo "Generated On 	: $generated_on"
	echo "Generated By 	: $generated_by"
	echo ""

	echo "$LINE_MINOR"
	echo "BASIC STATISTICS"
	echo "$LINE_MINOR"
	echo "Total Lines 	: $TOTAL_LINES"
	echo "ERROR Count 	: $ERROR_COUNT"
	echo "WARNING Count 	: $WARNING_COUNT"
	echo "INFO Count	: $INFO_COUNT"		#improvement - printing
	echo ""

	echo "$LINE_MINOR"
	echo "TOP $TOP_N FREQUENT WORDS"
	echo "$LINE_MINOR"
	if [[ ${#TOP_WORDS[@]} -eq 0 ]]; then			#check if the TOP_WORDS array is empty
		echo "No meaningful words found"
	else
		printf '%s\n' "${TOP_WORDS[@]}"			#print the words, each on new line
	fi
	echo ""

	echo "$LINE_MINOR"
	echo "END OF REPORT"
	echo "$LINE_MINOR"
}


write_summary(){
	local log_file="$1"
	if ! generate_report "$log_file" > "$SUMMARY_FILE"; then			#check if the summary writting failed
		error_exit "could not write '$SUMMARY_FILE'." "$EXIT_WRITE_FAILED"
	fi
}


main(){
	validate_input "$#" "${1:-}"			#call the function and pass number of args and the log file

	local log_file="$1"				#store the log file to analyze

	compute_statistics "$log_file"

	compute_top_words "$log_file"

	write_summary "$log_file"
	cat "$SUMMARY_FILE"

	exit "$EXIT_SUCCESS"				#return the success exit code (0) if everything pass
}

main "$@"						#pass all arguments to main function
